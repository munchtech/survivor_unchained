"""Proof without ears for the den's sound (lane F): the table of every new event (how often it fired in a den run, how often the
limiter held it back, its peak level) and an offline replica of the mixer's master over the boss fight.

    set DEN_SOUND_RUN=<csv>; dotnet test godot/tests --filter DenSoundRunTests     (the harness's den run, the layer's rules over its events)
    python tools/sound/den_proof.py <csv> [docs/team/den_sound_run.md]

The log is seed,t,id,played|held,x,z. The replica puts each played voice (its loudest take, full strength: the worst case), the
boss track, the den's bed and the pits through the Synth's master as written (bus levels and sends from data/content/sounds.json;
compressor -16 dB, 4:1, 4 ms / 250 ms; makeup; limiter at -1 dBFS, instant down, 80 ms back). It carries only the den layer: the
game's own hit and swing sounds are not in the log, so its figures are the den layer's share, not the whole mix.
"""
import json
import math
import re
import sys
from collections import defaultdict
from pathlib import Path

import numpy as np
import soundfile as sf

ROOT = Path(__file__).resolve().parents[2]
SND = ROOT / "godot" / "art" / "sound"
RATE = 44100


def data():
    s = (ROOT / "godot" / "data" / "content" / "sounds.json").read_text(encoding="utf-8")
    return json.loads(re.sub(r"^\s*//.*$", "", s, flags=re.M))


def takes(family):
    n = json.loads((SND / "sounds.json").read_text())[family]
    out = []
    for i in range(n):
        x, r = sf.read(SND / f"{family}_{i}.wav", dtype="float32", always_2d=True)
        assert r == RATE, (family, r)
        out.append(x if x.shape[1] == 2 else np.repeat(x, 2, axis=1))
    return out


def db(x):
    return 20 * math.log10(max(x, 1e-9))


def peak_db(family):
    return db(max(float(np.abs(t).max()) for t in takes(family)))


def master(left, right, wl, wr, level, makeup):
    """The Synth's master dynamics, sample by sample. Returns (out_left, out_right, max gain reduction dB, peak before, peak after)."""
    n = len(left)
    atk = 1 - math.exp(-1 / (0.004 * RATE)); rel = 1 - math.exp(-1 / (0.25 * RATE)); lrel = 1 - math.exp(-1 / (0.08 * RATE))
    ceil, thr, ratio = 0.891, -16.0, 4.0
    env = 0.0; limg = 1.0
    out = np.zeros((n, 2), dtype=np.float32)
    pk_in = np.maximum(np.abs(left + wl * 0.35), np.abs(right + wr * 0.35)) * level
    worst = 0.0
    for i in range(n):
        pk = float(pk_in[i])
        env += (pk - env) * (atk if pk > env else rel)
        over = 20 * math.log10(env) - thr if env > 1e-6 else -120
        dyn = 10 ** (-over * (1 - 1 / ratio) / 20) if over > 0 else 1.0
        dyn *= makeup
        post = pk * dyn * limg
        if post > ceil:
            limg = ceil / (pk * dyn)
        else:
            limg += (1 - limg) * lrel
        dyn *= limg * level
        out[i, 0] = left[i] * dyn; out[i, 1] = right[i] * dyn
        worst = max(worst, -20 * math.log10(max(dyn / (level * makeup), 1e-9)))
    return out, worst, float(pk_in.max()), float(np.abs(out).max())


def main():
    log = Path(sys.argv[1]).read_text().splitlines()
    dst = Path(sys.argv[2]) if len(sys.argv) > 2 else ROOT / "docs" / "team" / "den_sound_run.md"
    d = data()
    ev, buses = d["events"], d["buses"]
    rows = [l.split(",") for l in log if l.strip()]
    seeds = sorted({int(r[0]) for r in rows})
    fired = defaultdict(int); held = defaultdict(int)
    for s, t, i, st, x, z in rows:
        (fired if st == "played" else held)[i] += 1
    # every id the den layer plays
    ids = sorted({i for i in ev if i.startswith(("voice.", "her.", "den.", "music.den.", "bed.den")) or i in ("dodge.perfect", "heartbeat")})
    out = ["# The den's sound events, as a den run fires them (generated by tools/sound/den_proof.py)", "",
           f"The harness's deft bot, seeds {', '.join(map(str, seeds))}, the Hollow at level 6 (godot/tests/DenSoundRunTests.cs: the real sim's events through "
           "the real rules: DenSound.Wants, the VoiceLimiter, HerVoice, MusicRule, PackFarRule). Fired = played, summed over the six runs (about nine minutes each); held = kept back by the limiter. "
           "Peak = the loudest take's peak at the master's input, at full strength (take peak + layer gain + bus level), dBFS.", "",
           "| event | bus | takes | fired | held | peak dBFS (master input) |", "|---|---|---|---|---|---|"]
    peaks = {}
    for i in ids:
        e = ev[i]
        bus = e.get("bus", "sfx")
        lvl = db(buses[bus]["level"])
        pk = max(peak_db(l["take"]) + db(l.get("gain", 1)) + lvl for l in e["layers"])
        peaks[i] = pk
        n = sum(json.loads((SND / "sounds.json").read_text())[l["take"]] for l in e["layers"])
        out.append(f"| {i} | {bus} | {n} | {fired.get(i, 0)} | {held.get(i, 0)} | {pk:.1f} |")
    for i in sorted(set(fired) | set(held)):
        if i not in ev and not i.startswith("music.den."):
            out.append(f"| {i} (a duck on the music bus, not a take) | | | {fired.get(i, 0)} | {held.get(i, 0)} | |")
    music = sorted((i, fired[i]) for i in fired if i.startswith("music.den."))
    out += ["", "Score changes logged (all seeds): " + ", ".join(f"{i} x{n}" for i, n in music), ""]

    # the boss fight, replicated: the window from the boss track's start to the end of the sting, seed by seed
    out += ["## Master bus over the boss fight (offline replica of Synth's master, den layer only)", "",
            "| seed | window (s) | pre-limiter peak (dBFS) | after the master (dBFS) | worst gain reduction (dB) | clipped samples |", "|---|---|---|---|---|---|"]
    for seed in seeds:
        sr = [(float(t), i, st) for s, t, i, st, x, z in rows if int(s) == seed]
        boss = [t for t, i, st in sr if i == "music.den.boss"]
        fall = [t for t, i, st in sr if i == "music.den.falls.off" or i == "music.den.falls"]
        if not boss:
            out.append(f"| {seed} | (no boss fight: she fell first) | | | | |"); continue
        t0 = boss[0]; t1 = (max(fall) if fall else t0 + 120) + 3
        t0 = max(0.0, t0 - 4)
        n = int((t1 - t0) * RATE)
        L = np.zeros(n); R = np.zeros(n); WL = np.zeros(n); WR = np.zeros(n)

        def add(x, at, gain, bus):
            a = int((at - t0) * RATE)
            if a >= n:
                return
            x = x * gain * buses[bus]["level"]
            b = min(n, a + len(x))
            lo = max(a, 0)
            seg = x[lo - a: b - a]
            L[lo:b] += seg[:, 0]; R[lo:b] += seg[:, 1]
            WL[lo:b] += seg[:, 0] * buses[bus].get("send", 0); WR[lo:b] += seg[:, 1] * buses[bus].get("send", 0)

        def loop(x, a, b, gain, bus):
            m = int((b - a) * RATE)
            idx = (np.arange(m) % len(x))
            add(x[idx], a, gain, bus)

        # beds: the den's air and the pits, under the whole window; the boss track from its start, the sting at the death
        loop(takes("den_ambience")[0], t0, t1, 1.0, "ambience")
        loop(takes("den_pits")[0], t0, t1, 1.0, "ambience")
        loop(takes("music_den_boss")[0], boss[0], (min(fall) if fall else t1), 1.0, "music")
        if fall:
            add(takes("music_den_falls")[0], min(fall), 1.0, "music")
        for t, i, st in sr:
            if st != "played" or t < t0 or t > t1 or i not in ev or i.startswith(("music.", "den.", "bed.")):
                continue
            e = ev[i]
            for lay in e["layers"]:
                best = max(takes(lay["take"]), key=lambda x: float(np.abs(x).max()))
                add(best, t, lay.get("gain", 1), e.get("bus", "sfx"))
        mk = 10 ** (d["buses"]["master"].get("makeup", 0) / 20)
        res, gr, pre, post = master(L, R, WL, WR, d["buses"]["master"]["level"], mk)
        clipped = int((np.abs(res) > 0.891 + 1e-4).sum())
        out.append(f"| {seed} | {t0:.0f}-{t1:.0f} | {db(pre * mk):.1f} | {db(post):.1f} | {gr:.1f} | {clipped} |")
    out += ["", "A sample over -1 dBFS (0.891) after the master is a clip; the limiter holds the ceiling by construction, and the count above is the check."]
    dst.write_text("\n".join(out) + "\n", encoding="utf-8")
    print("\n".join(out))


if __name__ == "__main__":
    main()
